function targetLanguage(language: string): LocalisedLanguage | null {
  if (language === "hindi") return "hindi"
  if (language === "gujarati") return "gujarati"
  return null
}

export function localizeOptionLabel(label: string, language: string): string {
  const target = targetLanguage(language)
  if (!target) return label
  return LABELS[target][label] || label
}

export function localizeSignatureItemsLabel(industry: string, language: string): string {
  const target = targetLanguage(language)
  if (!target) return ""
  const key = (industry || "OTHER").toUpperCase()
  return SIGNATURE_HEADINGS[target][key] || SIGNATURE_HEADINGS[target].OTHER
}

export function localizeSpecialMentionPlaceholder(
  industry: string,
  moodKey: "positive" | "neutral" | "negative",
  language: string,
): string {
  const target = targetLanguage(language)
  if (!target) return ""
  const key = (industry || "OTHER").toUpperCase()
  const entry = SPECIAL_PLACEHOLDERS[target][key] || SPECIAL_PLACEHOLDERS[target].DEFAULT
  return entry[moodKey]
}

export function mcqText(language: string, key: string): string {
  const target = targetLanguage(language)
  if (!target) return ""
  return UI[target][key] || ""
}
